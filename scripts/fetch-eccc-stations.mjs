#!/usr/bin/env node
// Fetch Environment Canada's citypage_weather site list and emit a typed
// lookup table at src/lib/weather/eccc-stations.ts. Run manually when ECCC
// publishes a revised list — there's no runtime dependency on this script,
// so it stays out of CI.
//
// Source: https://dd.weather.gc.ca/today/citypage_weather/docs/site_list_en.csv
//
// CSV shape (no quoting, 2 header rows):
//   line 1: "Site Names,,,,"
//   line 2: "Codes,English Names,Province Codes,Latitude,Longitude"
//   rows:   s0000001,Athabasca,AB,54.72N,113.28W
//
// Rows with an HEF (highway-event feed) province code carry empty lat/lon
// and are dropped — they're advisories, not forecast points.

import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const SOURCE_URL =
  'https://dd.weather.gc.ca/today/citypage_weather/docs/site_list_en.csv';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = resolve(__dirname, '../src/lib/weather/eccc-stations.ts');

function parseCoord(raw) {
  // Format: "45.40N" / "75.69W". North/East positive, South/West negative.
  const m = /^(-?\d+(?:\.\d+)?)([NSEW])$/.exec(raw.trim());
  if (!m) return null;
  const value = parseFloat(m[1]);
  return m[2] === 'S' || m[2] === 'W' ? -value : value;
}

async function main() {
  process.stderr.write(`Fetching ${SOURCE_URL}…\n`);
  const res = await fetch(SOURCE_URL);
  if (!res.ok) {
    throw new Error(`ECCC site list fetch failed: HTTP ${res.status}`);
  }
  const csv = await res.text();

  const lines = csv.split(/\r?\n/).filter(Boolean);
  // Drop the 2 header rows
  const dataLines = lines.slice(2);

  const stations = [];
  let skipped = 0;
  for (const line of dataLines) {
    const parts = line.split(',');
    if (parts.length !== 5) {
      skipped++;
      continue;
    }
    const [site, name, prov, latRaw, lonRaw] = parts.map((s) => s.trim());
    if (!site || !name || !prov || !latRaw || !lonRaw) {
      skipped++;
      continue;
    }
    const lat = parseCoord(latRaw);
    const lon = parseCoord(lonRaw);
    if (lat == null || lon == null) {
      skipped++;
      continue;
    }
    stations.push({ site, prov, name, lat, lon });
  }

  stations.sort((a, b) => a.site.localeCompare(b.site));

  process.stderr.write(
    `Parsed ${stations.length} stations (${skipped} skipped).\n`,
  );

  const generated = new Date().toISOString().slice(0, 10);
  const header = `// Generated by scripts/fetch-eccc-stations.mjs on ${generated}.
// Source: ${SOURCE_URL}
// Do not hand-edit — rerun the script to refresh.

export interface EcccStation {
  /** Site identifier, e.g. "s0000430". */
  readonly site: string;
  /** Two-letter province code, e.g. "ON". */
  readonly prov: string;
  /** Human-readable English name. */
  readonly name: string;
  /** Latitude in decimal degrees (north positive). */
  readonly lat: number;
  /** Longitude in decimal degrees (east positive). */
  readonly lon: number;
}

`;

  const body =
    `export const ECCC_STATIONS: readonly EcccStation[] = Object.freeze([\n` +
    stations
      .map((s) => {
        const name = s.name.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
        return `  { site: '${s.site}', prov: '${s.prov}', name: '${name}', lat: ${s.lat}, lon: ${s.lon} },`;
      })
      .join('\n') +
    `\n]);\n`;

  writeFileSync(OUTPUT_PATH, header + body, 'utf8');
  process.stderr.write(`Wrote ${OUTPUT_PATH}\n`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
