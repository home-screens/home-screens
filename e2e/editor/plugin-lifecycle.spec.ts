test('a plugin exporting deriveProvidedKeys advertises its keys in the condition picker', async ({ page, request }) => {
  const server = await serveTarball(RICH_TARBALL);
  try {
    await installTarball(request, server.origin);

    // A background-provider instance (config.entity=sensor) whose bundle derives
    // a state key from that config, plus a text module whose visibility picker
    // should offer the derived, namespaced key.
    const provider = pluginModule(RICH_TYPE, {
      id: 'rich-provider',
      position: { x: 100, y: 500 },
      backgroundProvider: true,
      config: { entity: 'sensor' },
    });
    const gated = textModule('GATED', {
      visibility: { conditions: [{ kind: 'state', sourceKey: '', equals: '' }] },
    });
    await putConfig(request, baseConfig({ screens: [makeScreen('s1', 'S1', [provider, gated])] }));

    await page.goto('/editor');
    await expect(page.getByTestId('editor-canvas')).toBeVisible();
    // Gate on the plugin actually being loaded/registered: its provider instance
    // renders live on the canvas, so its marker proves registration completed
    // before collectProvidedStateKeys runs for the picker.
    await expect(page.locator('[data-plugin-marker="e2e-rich"]')).toBeVisible();

    await page.locator('[data-module-id="text-gated"]').click();
    await page.getByRole('button', { name: 'Conditions' }).click();

    // Focusing the key input opens the custom suggestion dropdown, sourced from
    // collectProvidedStateKeys → the plugin's namespaced derived key.
    await page.getByLabel('State key').click();
    await expect(
      page.getByRole('option').filter({ hasText: `${RICH_TYPE}:sensor` }),
    ).toBeVisible();
  } finally {
    await server.close();
  }
});

