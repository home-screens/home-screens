/**
 * Plugin lifecycle, end to end.
 *
 * Unlike display/plugins.spec.ts (which pre-seeds the fixture plugin straight
 * onto disk with seedFixturePlugin, skipping the install pipeline), these specs
 * drive the *real* install path: a committed .tar.gz is downloaded and run
 * through `/api/plugins/install-external` (extract → validate → promote →
 * installed.json) before the plugin ever renders.
 *
 * The download is normally a server-side fetch Playwright can't intercept, but
 * `validateExternalUrl` deliberately allows `http://127.0.0.1` as a
 * dev/test escape hatch (and the SSRF IP guard only runs for https), so a
 * throwaway loopback HTTP server serving the tarball bytes lets the Next
 * server fetch it exactly as it would a marketplace CDN.
 *
 * The install fixtures live in e2e/fixtures/plugins/ and are regenerated by
 * build-plugin-fixtures.mjs; the minimal one mirrors seedFixturePlugin's
 * content byte-for-byte so "the fixture plugin" behaves identically whether
 * seeded or installed.
 */

const FIXTURES_DIR = path.join(__dirname, '..', 'fixtures', 'plugins');
const MINIMAL_TARBALL = path.join(FIXTURES_DIR, 'e2e-fixture-plugin.tar.gz');
const RICH_TARBALL = path.join(FIXTURES_DIR, 'e2e-fixture-rich-plugin.tar.gz');

const MINIMAL_TYPE = 'plugin:e2e-fixture';
const RICH_TYPE = 'plugin:e2e-fixture-rich';
const RICH_GREETING = 'GREETING FROM PLUGIN I18N';

interface LocalServer {
  origin: string;
  close: () => Promise<void>;
}

/**
 * A loopback HTTP server with permissive CORS (dev plugins fetch cross-origin).
 * Binds on all interfaces so either `127.0.0.1` or `localhost` reaches it; the
 * `hostname` only picks which name goes in the returned origin. Server-side
 * downloads (install-external) use `127.0.0.1`; browser fetches (dev mode) must
 * use `localhost` because the app CSP's connect-src allows `http://localhost:*`
 * but not the raw loopback IP.
 */
async function startServer(handler: http.RequestListener, hostname = '127.0.0.1'): Promise<LocalServer> {
  const server = http.createServer((req, res) => {
    res.setHeader('Access-Control-Allow-Origin', '*');
    res.setHeader('Access-Control-Allow-Methods', 'GET,HEAD,OPTIONS');
    res.setHeader('Access-Control-Expose-Headers', 'ETag, Content-Length');
    if (req.method === 'OPTIONS') {
      res.writeHead(204);
      res.end();
      return;
    }
    handler(req, res);
  });
  await new Promise<void>((resolve) => server.listen(0, resolve));
  const { port } = server.address() as AddressInfo;
  return {
    origin: `http://${hostname}:${port}`,
    close: () => new Promise<void>((resolve) => server.close(() => resolve())),
  };
}

/** Serve a single tarball file's bytes for any request path. */
async function serveTarball(tarballPath: string): Promise<LocalServer> {
  const bytes = readFileSync(tarballPath);
  return startServer((req, res) => {
    const headers = { 'content-type': 'application/gzip', 'content-length': String(bytes.length) };
    if (req.method === 'HEAD') {
      res.writeHead(200, headers);
      res.end();
      return;
    }
    res.writeHead(200, headers);
    res.end(bytes);
  });
}

/** Install a plugin tarball through the real install-external pipeline. */
async function installTarball(
  request: APIRequestContext,
  origin: string,
): Promise<{ pluginId: string; version: string }> {
  const res = await request.post('/api/plugins/install-external', {
    data: { tarballUrl: `${origin}/plugin.tar.gz` },
  });
  expect(res.ok()).toBe(true);
  const body = await res.json();
  expect(body).toMatchObject({ ok: true });
  return body;
}

function pluginModule(type: string, overrides: Partial<ModuleInstance> = {}): ModuleInstance {
  return {
    id: 'plugin-instance',
    type,
    position: { x: 100, y: 100 },
    size: { w: 320, h: 200 },
    zIndex: 1,
    style: { ...DEFAULT_MODULE_STYLE },
    config: {},
    ...overrides,
  } as ModuleInstance;
}

// ---------------------------------------------------------------------------
// Install happy path — real tarball through the install pipeline, then render
// ---------------------------------------------------------------------------

test('installing a tarball registers the module type and renders it on the display', async ({ page, request }) => {
  const server = await serveTarball(MINIMAL_TARBALL);
  try {
    const installed = await installTarball(request, server.origin);
    expect(installed).toMatchObject({ pluginId: 'e2e-fixture', version: '1.0.0' });

    // Install persisted an enabled entry (module type now registrable).
    const listRes = await request.get('/api/plugins/installed');
    expect(listRes.ok()).toBe(true);
    const list = await listRes.json();
    expect(list.plugins).toContainEqual(
      expect.objectContaining({ id: 'e2e-fixture', moduleType: 'e2e-fixture', enabled: true }),
    );

    await putConfig(request, baseConfig({
      screens: [makeScreen('s1', 'S1', [pluginModule(MINIMAL_TYPE, { config: { label: 'INSTALLED RENDER OK' } })])],
    }));
    await page.goto('/display');

    // The loader fetches the just-installed manifest + bundle and renders it.
    await expect(page.locator('[data-plugin-marker="e2e"]')).toBeVisible();
    await expect(page.getByText('INSTALLED RENDER OK')).toBeVisible();
  } finally {
    await server.close();
  }
});

// The committed tarball is generated from seedFixturePlugin's exported source,
// but it's a static binary — nothing regenerates it at test time. Without this
// guard, editing the seed bundle would silently leave the tarball stale (the
// install path and the seed path read different byte sources, so no other test
// would catch it). Untar and compare to fail loudly on drift instead.
test('the committed install tarball has not drifted from the seedFixturePlugin source', () => {
  const tmp = mkdtempSync(path.join(os.tmpdir(), 'hs-tarball-parity-'));
  try {
    execFileSync('tar', ['-xzf', MINIMAL_TARBALL, '-C', tmp]);
    const root = path.join(tmp, 'e2e-fixture');
    const manifest = JSON.parse(readFileSync(path.join(root, 'manifest.json'), 'utf-8'));
    const bundle = readFileSync(path.join(root, 'dist', 'bundle.js'), 'utf-8');
    expect(manifest).toEqual(FIXTURE_MANIFEST);
    expect(bundle).toBe(FIXTURE_BUNDLE);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
});

