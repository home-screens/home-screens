// Dev mode — load from a dev server, then reload a changed bundle (the swap)
// ---------------------------------------------------------------------------

const DEV_MANIFEST = {
  id: 'e2e-dev',
  name: 'E2E Dev Plugin',
  version: '1.0.0',
  description: 'E2E dev-mode plugin',
  author: 'e2e',
  license: 'MIT',
  minAppVersion: '1.0.0',
  moduleType: 'e2e-dev',
  category: 'Media & Display',
  icon: 'Code2',
  defaultConfig: {},
  defaultSize: { w: 320, h: 200 },
  exports: { component: 'default' },
};

function devBundle(label: string): string {
  return `(function(){var R=window.React;window.__HS_PLUGIN__={default:function(){`
    + `return R.createElement('div',{'data-plugin-marker':'e2e-dev'},'${label}');}};})();`;
}

/** A dev server whose served bundle can be swapped to simulate an edit. */
async function startDevServer(): Promise<LocalServer & { setBundle: (label: string) => void }> {
  let bundle = devBundle('DEV V1');
  let etag = 1;
  const manifestBody = JSON.stringify(DEV_MANIFEST);
  const server = await startServer((req, res) => {
    const url = new URL(req.url ?? '/', 'http://local');
    if (url.pathname === '/manifest.json') {
      const headers = { 'content-type': 'application/json', 'content-length': String(Buffer.byteLength(manifestBody)) };
      res.writeHead(200, headers);
      res.end(req.method === 'HEAD' ? undefined : manifestBody);
      return;
    }
    if (url.pathname === '/dist/bundle.js') {
      const headers = {
        'content-type': 'application/javascript',
        'content-length': String(Buffer.byteLength(bundle)),
        etag: `"${etag}"`,
      };
      res.writeHead(200, headers);
      res.end(req.method === 'HEAD' ? undefined : bundle);
      return;
    }
    res.writeHead(404);
    res.end();
  }, 'localhost');
  return {
    ...server,
    setBundle: (label: string) => {
      bundle = devBundle(label);
      etag += 1;
    },
  };
}

test('a dev-mode plugin loads from a dev server and re-registers a changed bundle', async ({ page, request }) => {
  const dev = await startDevServer();
  try {
    await putConfig(request, baseConfig({
      settings: { advancedMode: true },
      screens: [makeScreen('s1', 'S1', [pluginModule('plugin:e2e-dev', { id: 'dev-mod', config: {} })])],
    }));

    await page.goto('/editor');
    await expect(page.getByTestId('editor-canvas')).toBeVisible();

    const loadDev = async () => {
      await page.getByRole('button', { name: 'Plugins' }).click();
      const dialog = page.getByRole('dialog', { name: 'Plugins' });
      await dialog.getByRole('button', { name: 'Developer' }).click();
      await dialog.getByPlaceholder('http://localhost:5173').fill(dev.origin);
      await dialog.getByRole('button', { name: 'Load', exact: true }).click();
      // Loaded dev plugins are listed by name; wait for it before closing.
      await expect(dialog.getByText('E2E Dev Plugin')).toBeVisible();
      await page.getByRole('button', { name: 'Close dialog' }).click();
      await expect(dialog).toBeHidden();
    };

    // Initial load: the dev bundle registers and renders live on the canvas.
    await loadDev();
    await expect(page.locator('[data-plugin-marker="e2e-dev"]')).toHaveText('DEV V1');

    // Edit the bundle server-side, then reload it. loadDevPlugin re-executes the
    // new bundle and swaps the registered component (the same path the 2s poll
    // takes on an ETag/length change) — the canvas re-renders the new output.
    dev.setBundle('DEV V2');
    await loadDev();
    await expect(page.locator('[data-plugin-marker="e2e-dev"]')).toHaveText('DEV V2');
  } finally {
    await dev.close();
  }
});
