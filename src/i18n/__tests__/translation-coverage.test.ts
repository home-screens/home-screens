/**
 * Per-locale allowance for anything not covered by the two lists above. Zero
 * everywhere: every shipped locale is fully translated. Lower a number when
 * you translate more; never raise one to make a build pass.
 */
const BUDGETS: Readonly<Record<string, number>> = {
  'da-DK': 0,
  'de-DE': 0,
  'es-ES': 0,
  'fr-FR': 0,
  'nl-NL': 0,
  'pt-BR': 0,
};

/**
 * Values with no letters at all (numbers, symbols, `{count}%`) can never be
 * "translated". Deliberately no minimum length: an earlier `length > 2` guard
 * hid 37 short entries, among them real misses like `" of "`, `"or"`, `"Up"`,
 * `"To"` and `"No"` sitting untranslated in da-DK. Short symbols that really
 * are universal (`OK`, `ID`, `X`/`Y`, `O₃`, `AM`/`PM`) belong in one of the
 * allowlists, where the decision is visible, rather than in a length rule.
 */
function isTranslatable(value: unknown): boolean {
  if (typeof value !== 'string') return true;
  return /\p{L}/u.test(value);
}

/** Plural-form objects arrive whole from `flatten`; compare them structurally. */
function sameValue(a: unknown, b: unknown): boolean {
  if (typeof a === 'string' && typeof b === 'string') return a === b;
  return JSON.stringify(a) === JSON.stringify(b);
}

function untranslatedKeys(locale: string): string[] {
  const out: string[] = [];
  const localeAllow = LOCALE_UNTRANSLATABLE[locale] ?? new Set<string>();
  for (const ns of BUILT_IN_NAMESPACES) {
    const baseline = loadDict(FALLBACK_LOCALE, ns);
    const dict = loadDict(locale, ns);
    if (!baseline || !dict) continue;
    const en = flatten(baseline);
    const loc = flatten(dict);
    for (const [key, value] of Object.entries(en)) {
      const id = `${ns}|${key}`;
      if (SHARED_UNTRANSLATABLE.has(id) || localeAllow.has(id)) continue;
      if (typeof value === 'string' && !isTranslatable(value)) continue;
      if (sameValue(loc[key], value)) out.push(id);
    }
  }
  return out;
}

describe('translation coverage (untranslated-value ratchet)', () => {
  const locales = Object.keys(LOCALES).filter((l) => l !== FALLBACK_LOCALE);

  for (const locale of locales) {
    const budget = BUDGETS[locale];

    it(`${locale}: no more than ${budget ?? 0} values left identical to en-US`, () => {
      expect(budget, `${locale} has no entry in BUDGETS`).toBeDefined();
      const found = untranslatedKeys(locale);
      const overflow = found.slice(0, 25).join('\n  ');
      expect(
        found.length,
        `${locale} has ${found.length} values identical to en-US (budget ${budget}).\n` +
          `Translate them, or add genuinely-untranslatable entries to SHARED_UNTRANSLATABLE.\n  ${overflow}`,
      ).toBeLessThanOrEqual(budget);
    });

    it(`${locale}: budget is not stale`, () => {
      const found = untranslatedKeys(locale);
      expect(
        found.length,
        `${locale} now has only ${found.length} untranslated values — lower its BUDGETS entry to ${found.length}.`,
      ).toBeGreaterThanOrEqual(budget);
    });
  }
});

/**
 * Every built-in module needs a `registry.types.<type>` label in every locale.
 *
 * The palette, canvas, and PropertyPanel all render `t('registry.types.' + type)`,
 * so a missing entry ships the raw key as the module's name. The untranslated-value
 * ratchet above cannot catch it: it only compares keys that exist in en-US against
 * their locale counterparts, and a type absent from *every* dictionary is invisible
 * to it. (fullscreen-weather shipped with exactly this gap.)
 */
describe('registry module labels', () => {
  const builtinTypes = getAllModuleDefinitions()
    .map((d) => d.type)
    .filter((t) => !t.startsWith('plugin:'));

  for (const locale of Object.keys(LOCALES)) {
    it(`${locale}: every built-in module type has a registry label`, () => {
      const dict = loadDict(locale, 'editor') as
        | { registry?: { types?: Record<string, unknown> } }
        | null;
      const types = dict?.registry?.types ?? {};
      const missing = builtinTypes.filter((t) => typeof types[t] !== 'string' || !types[t]);
      expect(
        missing,
        `${locale} is missing registry.types entries for: ${missing.join(', ')}`,
      ).toEqual([]);
    });
  }
});
